"""Camera Hunter (hue_hunt): colors.csv + XKCD rgb.txt -> scripts/games/hue_hunt/hue_hunt_colors.gd

    python tools/hue_hunt/build_colors.py <path to xkcd rgb.txt>

rgb.txt: https://xkcd.com/color/rgb.txt (CC0, media/licenses/XKCD_COLORS_CC0.md).
Hex values always come from rgb.txt; colors.csv only picks names and adds ES / tier / family.
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV = os.path.join(ROOT, "tools", "hue_hunt", "colors.csv")
OUT = os.path.join(ROOT, "scripts", "games", "hue_hunt", "hue_hunt_colors.gd")


def main() -> None:
    rgb = {}
    with open(sys.argv[1], encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                continue
            parts = line.rstrip("\n").split("\t")
            rgb[parts[0].strip()] = parts[1].strip()
    rows = list(csv.DictReader(open(CSV, encoding="utf-8")))
    missing = [r["name_en"] for r in rows if r["name_en"] not in rgb]
    if missing:
        sys.exit("not in rgb.txt: %s" % missing)
    lines = [
        "extends RefCounted",
        "",
        "## GENERATED by tools/hue_hunt/build_colors.py from tools/hue_hunt/colors.csv",
        "## + the XKCD colour survey (CC0). Don't edit by hand.",
        "## Each: [id, name_en, name_es, hex, tier, family]",
        "",
        "const COLORS := [",
    ]
    for r in rows:
        cid = r["name_en"].replace(" ", "_")
        lines.append('\t["%s", "%s", "%s", "%s", "%s", "%s"],' % (
            cid, r["name_en"], r["name_es"], rgb[r["name_en"]], r["tier"], r["family"]))
    lines.append("]")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d colours -> %s" % (len(rows), OUT))


if __name__ == "__main__":
    main()
