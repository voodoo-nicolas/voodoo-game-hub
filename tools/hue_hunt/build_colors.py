"""Camera Hunter (hue_hunt): colors.csv + XKCD rgb.txt -> scripts/games/hue_hunt/hue_hunt_colors.json

    python tools/hue_hunt/build_colors.py <path to xkcd rgb.txt>

rgb.txt: https://xkcd.com/color/rgb.txt (CC0, media/licenses/XKCD_COLORS_CC0.md).
Hex values always come from rgb.txt; colors.csv only picks names and adds ES / tier / family.
"""
import csv
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV = os.path.join(ROOT, "tools", "hue_hunt", "colors.csv")
OUT = os.path.join(ROOT, "scripts", "games", "hue_hunt", "hue_hunt_colors.json")


def main() -> None:
    rgb = {}
    with open(sys.argv[1], encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                continue
            parts = line.rstrip("\n").split("\t")
            rgb[parts[0].strip()] = parts[1].strip()
    rows = list(csv.DictReader(open(CSV, encoding="utf-8")))
    missing = [r["name_en"] for r in rows if r["name_en"] not in rgb]
    if missing:
        sys.exit("not in rgb.txt: %s" % missing)
    data = {"_readme": "GENERATED by tools/hue_hunt/build_colors.py from colors.csv + the XKCD colour survey (CC0). Each: [id, name_en, name_es, hex, tier, family].",
            "colors": [[r["name_en"].replace(" ", "_"), r["name_en"], r["name_es"], rgb[r["name_en"]], r["tier"], r["family"]] for r in rows]}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    nl = chr(10)
    with open(OUT, "w", encoding="utf-8", newline=nl) as f:
        f.write("{" + nl + ' "_readme": ' + json.dumps(data["_readme"]) + "," + nl + ' "colors": [' + nl)
        f.write(("," + nl).join("  " + json.dumps(c, ensure_ascii=False) for c in data["colors"]))
        f.write(nl + " ]" + nl + "}" + nl)
    print("%d colours -> %s" % (len(rows), OUT))


if __name__ == "__main__":
    main()
