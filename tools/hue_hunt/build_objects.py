"""Camera Hunter (hue_hunt): objects.csv -> scripts/games/hue_hunt/hue_hunt_objects.json

    python tools/hue_hunt/build_objects.py

Object / shape / property prompts for Object rounds (judged by the players' vote).
Own text (no licence needed). JSON so the string extractor skips it: names come with ES.
"""
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV = os.path.join(ROOT, "tools", "hue_hunt", "objects.csv")
OUT = os.path.join(ROOT, "scripts", "games", "hue_hunt", "hue_hunt_objects.json")


def main() -> None:
    rows = list(csv.DictReader(open(CSV, encoding="utf-8")))
    ids = [r["id"] for r in rows]
    assert len(ids) == len(set(ids)), "duplicate id"
    for r in rows:
        assert r["tier"] in ("easy", "medium", "hard") and r["theme"] in ("object", "shape", "property"), r
    nl = chr(10)
    with open(OUT, "w", encoding="utf-8", newline=nl) as f:
        f.write("{" + nl + ' "_readme": "GENERATED by tools/hue_hunt/build_objects.py from objects.csv. Each: [id, en, es, tier, theme].",' + nl + ' "objects": [' + nl)
        f.write(("," + nl).join("  " + json.dumps([r["id"], r["en"], r["es"], r["tier"], r["theme"]], ensure_ascii=False) for r in rows))
        f.write(nl + " ]" + nl + "}" + nl)
    print("%d prompts -> %s" % (len(rows), OUT))


if __name__ == "__main__":
    main()
