// Extracts the Voodoo IQ client data verbatim from the reference prototype
// (docs/voodoo-iq-prototype.html) into the voodoo_iq pack:
//   scripts/games/voodoo_iq/voodoo_iq_data.json
// EN/ES text (STR), section colors / icons, the brain map, and drawing palettes.
// Re-run after changing the prototype; never hand-edit the JSON.
//   deno run --allow-read --allow-write tools/iq_extract.ts
import { loadPrototype } from "../supabase/functions/_tests/prototype.ts";

const P = await loadPrototype("en", "STR, SEC_COLOR, SEC_ICON, BRAIN, CORSI_POS, TV_COL, TV_SIDE, NAT_COL, SKIN, HAIR, MX_SHAPES, LETTERS, CONF_LEVELS, IQ_DURS, BLITZ_DURS", "/* ============ App state");
const html = await Deno.readTextFile(new URL("../docs/voodoo-iq-prototype.html", import.meta.url));
const arr = (name: string) => JSON.parse(html.match(new RegExp(String.raw`const ${name} = (\[[^\]]*\]);`))![1].replaceAll("'", '"'));
const data = {
  _note: "GENERATED by tools/iq_extract.ts from docs/voodoo-iq-prototype.html. Do not edit.",
  STR: P.STR, SEC_COLOR: P.SEC_COLOR, SEC_ICON: P.SEC_ICON, SECS: P.SECS, CORE: P.CORE, BRAIN: P.BRAIN,
  CORSI_POS: P.CORSI_POS, TV_COL: P.TV_COL, TV_SIDE: P.TV_SIDE, NAT_COL: P.NAT_COL, SKIN: P.SKIN, HAIR: P.HAIR,
  MX_SHAPES: P.MX_SHAPES, LETTERS: P.LETTERS, CONF_LEVELS: P.CONF_LEVELS, IQ_DURS: P.IQ_DURS, BLITZ_DURS: P.BLITZ_DURS,
  GATE: P.GATE, COUNTRIES: arr("COUNTRIES"), AR_PROV: arr("AR_PROV"),
};
const out = new URL("../scripts/games/voodoo_iq/voodoo_iq_data.json", import.meta.url);
await Deno.writeTextFile(out, JSON.stringify(data, null, 1) + "\n");
console.log("wrote", out.pathname, Object.keys(data.STR.en).length, "EN keys,", Object.keys(data.STR.es).length, "ES keys");
